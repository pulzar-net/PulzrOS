#!/usr/bin/env python3
"""Turn the console's mark (console/public/icon.svg) into the pixel grid the
terminal logo draws.

    python3 scripts/render-logo.py            # rewrite the grid
    python3 scripts/render-logo.py --check    # fail if the grid is stale

The terminal logo is eight rows of half-block cells: sixteen pixels high. The
Pulzar mark is five nodes, the links between them, a core and an orbit ring,
and at sixteen pixels a downsample turns the links and the ring into a smear
of half-covered cells. So the SHAPE below is drawn by hand, against the SVG
rendered at that size with each part in a flat colour, and only the COLOURS
come from the SVG: each part takes its fill or stroke from icon.svg, the
light-scheme values, which is what a terminal's dark background shows best.

Reads the SVG as text: no Pillow, no renderer. The gateway reads the grid,
never the SVG.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "console/public/icon.svg"
OUTPUT = ROOT / "feed/pulzr-base/files/usr/share/pulzr/logo.txt"

# N: a node (.star). L: a link (.link). C: the core (.core). O: the orbit
# ring (the ellipse's stroke). '.': nothing.
SHAPE = [
    "......N.........",
    ".....NNN........",
    ".....NNN........",
    "......LLL.......",
    "......L..LNN....",
    "......L..LNNOOOO",
    ".....CCCL.L...OO",
    ".....CCC..L..OO.",
    "...OOOCLL.LOO...",
    "..OOLL..NNN.....",
    ".OO.L..ONNN.....",
    "OONN.OO.........",
    ".ONN..L.........",
    ".....NNN........",
    ".....NNN........",
    "......N.........",
]


def colours(svg):
    """Each part's colour, from the first (light-scheme) rule for its class
    and from the ellipse's own stroke."""
    def rule(cls, prop):
        m = re.search(r"\.%s\s*\{\s*%s:\s*(#[0-9a-fA-F]{6})" % (cls, prop), svg)
        if not m:
            raise SystemExit("icon.svg has no .%s { %s: #rrggbb }" % (cls, prop))
        return m.group(1)[1:].lower()

    ring = re.search(r'<ellipse[^>]*stroke="(#[0-9a-fA-F]{6})"', svg)
    if not ring:
        raise SystemExit("icon.svg has no ellipse with a stroke colour")
    return {
        "N": rule("star", "fill"),
        "L": rule("link", "stroke"),
        "C": rule("core", "fill"),
        "O": ring.group(1)[1:].lower(),
    }


def main():
    rgb = colours(SOURCE.read_text())
    cols, rows = len(SHAPE[0]), len(SHAPE)
    assert all(len(r) == cols for r in SHAPE), "SHAPE rows differ in width"

    lines = [
        "# The terminal logo: one row per pixel row, one token per pixel,",
        "# RRGGBB or - for nothing. Two pixel rows make one row of text.",
        "# Generated by scripts/render-logo.py from console/public/icon.svg.",
        "%d %d" % (cols, rows),
    ]
    for row in SHAPE:
        lines.append(" ".join("-" if kind == "." else rgb[kind] for kind in row))
    text = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        if OUTPUT.read_text() != text:
            print("%s is stale: run scripts/render-logo.py" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text)
    print("wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
