#!/usr/bin/env python3
"""Turn console/public/logo.png into the pixel grid the terminal logo draws.

    python3 scripts/render-logo.py            # rewrite the grid
    python3 scripts/render-logo.py --check    # fail if the grid is stale

The terminal logo is eight rows of half-block cells: sixteen pixels high. A
straight downsample to that size keeps the pin and loses the Z — the road's
three strokes are each thinner than one pixel and average into a blue smear.
So the SHAPE below is drawn by hand, against the PNG with an 11x16 grid laid
over it, and only the COLOURS come from the image: each pixel takes the colour
of the artwork nearest it in the same part of the mark, green for the
pin and blue for the road. That keeps the gradient and the road's darker edge
without letting a downsample decide what the letter looks like.

Needs Pillow, which is a developer dependency only. The gateway reads the
grid, never the PNG.
"""
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "console/public/logo.png"
OUTPUT = ROOT / "feed/parkeze-base/files/usr/share/parkeze/logo.txt"

# G: the pin. B: the road. '.': nothing.
SHAPE = [
    "...GGGGG...",
    "..GGGGGGG..",
    ".GGGGGGGGG.",
    ".GGG...GGG.",
    ".GGG...GGG.",
    ".GGG...GGG.",
    ".GGGGGGGGG.",
    ".GGGGGGGG..",
    ".GGGGGG....",
    ".GGGBBBB...",
    "..GBBBBBBB.",
    "......BBB..",
    "....BBB....",
    ".BBBB......",
    "BBBBBBBBB..",
    "..BBBBBBB..",
]


def part(rgb):
    r, g, b = rgb
    return "B" if b > g else "G"


def main():
    im = Image.open(SOURCE).convert("RGBA")
    im = im.crop(im.split()[3].getbbox())
    w, h = im.size
    cols, rows = len(SHAPE[0]), len(SHAPE)

    # Every opaque pixel of the artwork, by which part of the mark it is.
    points = {"G": [], "B": []}
    for y in range(0, h, 2):
        for x in range(0, w, 2):
            r, g, b, a = im.getpixel((x, y))
            if a >= 200:
                points[part((r, g, b))].append((x, y, (r, g, b)))

    lines = [
        "# The terminal logo: one row per pixel row, one token per pixel,",
        "# RRGGBB or - for nothing. Two pixel rows make one row of text.",
        "# Generated by scripts/render-logo.py from console/public/logo.png.",
        "%d %d" % (cols, rows),
    ]
    for j, row in enumerate(SHAPE):
        tokens = []
        for i, kind in enumerate(row):
            if kind == ".":
                tokens.append("-")
                continue
            cx, cy = (i + 0.5) * w / cols, (j + 0.5) * h / rows
            # The mean of the nearest few, not the nearest one: a single
            # point lands on a highlight or the shadow inside the pin's hole
            # often enough to speckle the gradient.
            near = sorted(points[kind],
                          key=lambda p: (p[0] - cx) ** 2 + (p[1] - cy) ** 2)[:24]
            rgb = tuple(round(sum(p[2][c] for p in near) / len(near)) for c in range(3))
            tokens.append("%02x%02x%02x" % rgb)
        lines.append(" ".join(tokens))
    text = "\n".join(lines) + "\n"

    if "--check" in sys.argv:
        if OUTPUT.read_text() != text:
            print("%s is stale: run scripts/render-logo.py" % OUTPUT.relative_to(ROOT))
            return 1
        return 0
    OUTPUT.write_text(text)
    print("wrote %s" % OUTPUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
