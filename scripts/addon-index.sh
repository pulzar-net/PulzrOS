#!/usr/bin/env bash
#
# What pulzr-base carries about this release's add-ons, from each
# feed/<name>/addon.
#
#   addon-index.sh <feed-dir> <payload-dir>
#
#   <payload-dir>/usr/share/pulzr/addons.caps       one line per add-on
#   <payload-dir>/lib/upgrade/keep.d/pulzr-addons   every add-on's keep.d
#
# Run by build-feed.sh into pulzr-base's payload, and by check-addons.sh and
# test-addon.sh into scratch directories, so all three read one generator.
#
# addons.caps is what the gateway itself decides with, never the catalog it
# downloads: which capabilities each add-on brings (so a deny can refuse one,
# or a dependency that brings one), the console feature word it turns on, the
# upstream release it carries, its title, and the paths a purge may delete.
# The catalog is display data from a server; this file came with the
# firmware, under the firmware's signature. Tab-separated:
#
#   name  feature|-  upstream|-  caps (space-separated)  title  keep (space-separated)
#
# The keep.d merge is why an add-on's configuration outlives the add-on. The
# add-on's own keep.d file only works while the package is installed, so a
# gateway whose restore failed and was then upgraded again would lose the
# buses somebody wrote. pulzr-base is always installed.

set -euo pipefail

FEED_DIR="${1:?feed dir}"
DATA="${2:?payload dir}"

die() { echo "error: $*" >&2; exit 1; }

caps_file="${DATA}/usr/share/pulzr/addons.caps"
keep_file="${DATA}/lib/upgrade/keep.d/pulzr-addons"
mkdir -p "$(dirname "${caps_file}")" "$(dirname "${keep_file}")"

{
  echo "# Generated by scripts/addon-index.sh from feed/*/addon. See pulzr-addon."
  printf '# name\tfeature\tupstream\tcaps\ttitle\tkeep\n'
} > "${caps_file}.new"
{
  echo "# Every add-on's configuration, kept across a firmware upgrade whether or"
  echo "# not the add-on is installed at the time: a restore that failed must not"
  echo "# cost the next upgrade the add-on's settings. Generated by"
  echo "# scripts/addon-index.sh from each add-on's own keep.d."
} > "${keep_file}.new"

keep_all=""
for pkgdir in "${FEED_DIR}"/*/; do
  [ -f "${pkgdir}/addon" ] || continue
  name="$(basename "${pkgdir}")"
  title="" caps="" feature=""
  # shellcheck disable=SC1091
  eval "$(. "${pkgdir}/addon"; printf 'title=%q caps=%q feature=%q' \
            "${ADDON_TITLE:-}" "${ADDON_CAPS:-}" "${ADDON_FEATURE:-}")"
  [ -n "${title}" ] || die "${name}/addon has no ADDON_TITLE"
  [ -n "${caps}" ] || die "${name}/addon has no ADDON_CAPS"
  case "${title}${caps}${feature}" in *$'\t'*) die "${name}/addon has a tab in a value" ;; esac
  # The upstream release the binary comes from, from the one place it is
  # pinned (an SDK recipe's PKG_VERSION, else a fetch's VERSION=); none for an
  # add-on that is only our own files.
  upstream="$(sed -n 's/^PKG_VERSION:=//p' "$(cd "${FEED_DIR}/.." && pwd)/sdk/packages/$(basename "${pkgdir}")/Makefile" 2>/dev/null | head -n1 || true)"
  [ -n "${upstream}" ] || upstream="$(sed -n 's/^VERSION=//p' "${pkgdir}/fetch" 2>/dev/null | head -n1 | tr -d '"' || true)"
  keep="$(cat "${pkgdir}"/files/lib/upgrade/keep.d/* 2>/dev/null \
            | grep -v '^[[:space:]]*\(#\|$\)' | tr -s '[:space:]' ' ' | sed 's/ $//' || true)"
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "${name}" "${feature:--}" "${upstream:--}" \
    "${caps}" "${title}" "${keep}" >> "${caps_file}.new"
  keep_all="${keep_all} ${keep}"
done

for path in ${keep_all}; do echo "${path}"; done | sort -u >> "${keep_file}.new"
mv "${caps_file}.new" "${caps_file}"
mv "${keep_file}.new" "${keep_file}"
